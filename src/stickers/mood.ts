/**
 * 从一句要发出去的回复里猜一个情绪。
 *
 * 只在一个地方用：主模型漏给 `stickerMood` 时的兜底。
 * 2026-11-19 的教训 —— 当天 10 条回复里 7 条没带情绪（某个群 10:40 之后全是裸文字），
 * 提示词里写「默认带表情」并不能保证模型真的给，所以「该配张图」的吐槽不能全指望它。
 *
 * 宁可猜成「无语」这种万金油，也别让回复干巴巴一行字。分寸（概率 / 冷却）由调用方把关。
 */
export function inferMood(text: string): string {
  const s = String(text ?? "");
  if (/哈哈|笑死|笑不活|绷不住|233|乐了/.test(s)) return "开心";
  if (/呵|就这|阴阳|笑你|你也配|摆烂|你说得对/.test(s)) return "嘲讽";
  if (/哇|居然|竟然|真的假的|假的吧|离谱/.test(s)) return "惊讶";
  if (/贴贴|爱你|抱抱|亲|想我/.test(s)) return "亲昵";
  if (/委屈|怪我|冤枉|难受|理亏/.test(s)) return "委屈";
  return "无语";
}